package com.example.aiweb.memory

import kotlinx.serialization.Serializable

/**
 * Жёсткие лимиты памяти (рабочей и долговременной): капы количества записей,
 * длин заголовков/текстов и допустимые значения дискриминаторов.
 * Единая точка правды — и хранилища, и ретривер сверяются с ней.
 */
object MemoryLimits {
    /** Максимум записей рабочей памяти в одной сессии. */
    const val WORKING_MAX_ENTRIES = 24

    /** Максимум символов в заголовке записи рабочей памяти. */
    const val WORKING_MAX_TITLE = 120

    /** Максимум символов в тексте записи рабочей памяти. */
    const val WORKING_MAX_CONTENT = 4000

    /** Максимум записей долговременной памяти (по всем видам суммарно). */
    const val LONG_MAX_ENTRIES = 200

    /** Максимум символов в заголовке записи долговременной памяти. */
    const val LONG_MAX_TITLE = 120

    /** Максимум символов в тексте записи долговременной памяти. */
    const val LONG_MAX_CONTENT = 2000

    /** Максимум тегов у записи долговременной памяти. */
    const val LONG_MAX_TAGS = 8

    /** Максимум символов в одном теге. */
    const val LONG_MAX_TAG_LEN = 24

    /** Допустимые виды долговременных записей. */
    val KINDS = listOf("profile", "decision", "knowledge")
}

/**
 * Запись рабочей памяти сессии (текущая задача): короткие заметки, живущие
 * ровно столько, сколько нужна сессия. Хранится по одному файлу на сессию.
 */
@Serializable
data class WorkingEntry(
    /** Идентификатор записи (уникален внутри сессии). */
    val id: String,
    /** Короткий заголовок. */
    val title: String,
    /** Текст заметки. */
    val content: String,
    /** Момент создания (мс), проставляется вызывающим. */
    val createdAt: Long,
    /** Момент последнего обновления (мс), проставляется хранилищем. */
    val updatedAt: Long
)

/**
 * Запись долговременной памяти (общая для всех сессий): профиль пользователя,
 * принятые решения и накопленные знания.
 */
@Serializable
data class MemoryEntry(
    /** Идентификатор записи (уникален в пределах хранилища). */
    val id: String,
    /** Вид записи: "profile" | "decision" | "knowledge" — см. [MemoryLimits.KINDS]. */
    val kind: String,
    /** Короткий заголовок. */
    val title: String,
    /** Текст записи. */
    val content: String,
    /** Теги для поиска/фильтрации (опционально). */
    val tags: List<String> = emptyList(),
    /** Кто создал запись: "user" | "agent". */
    val source: String = "user",
    /** Момент создания (мс), проставляется вызывающим. */
    val createdAt: Long,
    /** Момент последнего обновления (мс), проставляется хранилищем. */
    val updatedAt: Long
)
